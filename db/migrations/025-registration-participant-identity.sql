-- =====================================================================
--  025 - RegistrationID and ParticipantID become IDENTITY
--
--  Migration 019 documented that the application allocates the next id with
--  ISNULL(MAX(id), 0) + 1 inside the INSERT. The application no longer does
--  that: every create now omits the id and expects the database to supply
--  it, so on a database where these columns are still plain INT every
--  create fails with "Cannot insert the value NULL into column".
--
--  SQL Server cannot add IDENTITY to an existing column, so the table is
--  rebuilt: a shadow table is created with the same definition plus
--  IDENTITY, the rows are copied (ids preserved, so every foreign key still
--  points at the right row), the names are swapped, and the FKs and indexes
--  that pointed at the old table are recreated. The FK lists are read from
--  the catalog rather than hard-coded, so a child table added later is not
--  silently left behind.
--
--  Each table is rebuilt in its own transaction: if any step fails the
--  original table is still there, untouched.
--
--  Guarded and safe to re-run - a table that is already IDENTITY is skipped.
--  Apply to BOTH databases.
--
--  NOTE ON PERMISSIONS: the deploy login (wcpss-sql-writer) is db_ddladmin.
--  It can create and alter objects but cannot be granted EXECUTE on them and
--  cannot create database roles, so there is no helper procedure here: the
--  rebuild is generated by the catalog queries below and run with
--  sp_executesql, which needs no EXECUTE permission.
-- =====================================================================

SET NOCOUNT ON;
SET XACT_ABORT ON;
-- sqlcmd connects with QUOTED_IDENTIFIER OFF, and the tables carry indexes on
-- XML-typed columns, which cannot be created under that setting.
SET QUOTED_IDENTIFIER ON;
GO

DECLARE @schema SYSNAME = 'core';
DECLARE @table  SYSNAME;
DECLARE @idCol  SYSNAME;
DECLARE @pk     SYSNAME;
DECLARE @qualified NVARCHAR(200);
DECLARE @shadow    NVARCHAR(200);
DECLARE @copyCols NVARCHAR(MAX);
DECLARE @colDefs  NVARCHAR(MAX);
DECLARE @defaults NVARCHAR(MAX);
DECLARE @fksAdd   NVARCHAR(MAX);
DECLARE @fksDrop  NVARCHAR(MAX);
DECLARE @idx      NVARCHAR(MAX);
DECLARE @sql      NVARCHAR(MAX);

DECLARE rebuild CURSOR LOCAL FAST_FORWARD FOR
    -- Registration first: its FK to Participant is dropped and re-added as
    -- part of that rebuild, so Participant's own rebuild then sees a plain
    -- FK again.
    SELECT 'Registration', 'RegistrationID'
    UNION ALL
    SELECT 'Participant',  'ParticipantID';

OPEN rebuild;
FETCH NEXT FROM rebuild INTO @table, @idCol;

WHILE @@FETCH_STATUS = 0
BEGIN
    SET @qualified = QUOTENAME(@schema) + '.' + QUOTENAME(@table);
    SET @shadow    = QUOTENAME(@schema) + '.' + QUOTENAME(@table + '_new');

    -- Already done when the id is IDENTITY and the column defaults survived.
    IF COLUMNPROPERTY(OBJECT_ID(@qualified), @idCol, 'IsIdentity') = 1
       AND EXISTS (SELECT 1 FROM sys.default_constraints d
                     JOIN sys.columns c ON c.object_id = d.parent_object_id
                                       AND c.column_id = d.parent_column_id
                    WHERE d.parent_object_id = OBJECT_ID(@qualified)
                      AND c.name <> @idCol)
    BEGIN
        PRINT @qualified + '.' + @idCol + ' is already IDENTITY - skipping';
    END
    ELSE
    BEGIN
        PRINT 'Rebuilding ' + @qualified + ' with IDENTITY ' + @idCol;

        SET @pk = (SELECT name FROM sys.key_constraints
                    WHERE parent_object_id = OBJECT_ID(@qualified) AND type = 'PK');

        -- Columns to copy, and their definitions for the shadow table.
        -- Deliberately not SELECT INTO: that copies the id column too, and a
        -- column added by ALTER cannot be IDENTITY.
        SET @copyCols = STUFF((
            SELECT ',' + QUOTENAME(c.name)
              FROM sys.columns c
             WHERE c.object_id = OBJECT_ID(@qualified)
               AND c.name <> @idCol
               AND c.is_computed = 0
             ORDER BY c.column_id
               FOR XML PATH(''), TYPE).value('.', 'NVARCHAR(MAX)'), 1, 1, '');

        SET @colDefs = STUFF((
            SELECT ',' + QUOTENAME(c.name) + ' ' + TYPE_NAME(c.user_type_id)
                 + CASE WHEN TYPE_NAME(c.user_type_id) IN ('nvarchar', 'varchar', 'nchar', 'char')
                        THEN '(' + CASE WHEN c.max_length = -1 THEN 'MAX'
                                        WHEN TYPE_NAME(c.user_type_id) IN ('nvarchar', 'nchar')
                                        THEN CAST(c.max_length / 2 AS VARCHAR(10))
                                        ELSE CAST(c.max_length AS VARCHAR(10)) END + ')'
                        WHEN TYPE_NAME(c.user_type_id) IN ('decimal', 'numeric')
                        THEN '(' + CAST(c.precision AS VARCHAR(10)) + ',' + CAST(c.scale AS VARCHAR(10)) + ')'
                        ELSE '' END
                 + CASE WHEN c.is_nullable = 1 THEN ' NULL' ELSE ' NOT NULL' END
              FROM sys.columns c
             WHERE c.object_id = OBJECT_ID(@qualified)
               AND c.name <> @idCol
               AND c.is_computed = 0
             ORDER BY c.column_id
               FOR XML PATH(''), TYPE).value('.', 'NVARCHAR(MAX)'), 1, 1, '');

        -- Column defaults, re-added after the swap. Without them an INSERT
        -- that leaves a NOT NULL bit column out (IsLate, Attended, Source...)
        -- fails instead of taking the default.
        SET @defaults = (
            SELECT STRING_AGG(
                     'ALTER TABLE ' + @qualified + ' ADD CONSTRAINT ' + QUOTENAME(d.name)
                     + ' DEFAULT ' + d.definition + ' FOR ' + QUOTENAME(c.name),
                     ';')
              FROM sys.default_constraints d
              JOIN sys.columns c ON c.object_id = d.parent_object_id
                                AND c.column_id = d.parent_column_id
             WHERE d.parent_object_id = OBJECT_ID(@qualified)
               AND c.name <> @idCol);

        -- Every FK that points at this table, as drop and re-add statements.
        SET @fksDrop = (
            SELECT STRING_AGG(
                     'ALTER TABLE ' + QUOTENAME(OBJECT_SCHEMA_NAME(fk.parent_object_id)) + '.'
                     + QUOTENAME(OBJECT_NAME(fk.parent_object_id))
                     + ' DROP CONSTRAINT ' + QUOTENAME(fk.name),
                     ';')
              FROM sys.foreign_keys fk
             WHERE fk.referenced_object_id = OBJECT_ID(@qualified));

        SET @fksAdd = (
            SELECT STRING_AGG(
                     'ALTER TABLE ' + QUOTENAME(OBJECT_SCHEMA_NAME(fk.parent_object_id)) + '.'
                     + QUOTENAME(OBJECT_NAME(fk.parent_object_id))
                     + ' WITH CHECK ADD CONSTRAINT ' + QUOTENAME(fk.name)
                     + ' FOREIGN KEY (' + fkc.parent_col + ')'
                     + ' REFERENCES ' + QUOTENAME(OBJECT_SCHEMA_NAME(fk.referenced_object_id)) + '.'
                     + QUOTENAME(OBJECT_NAME(fk.referenced_object_id)) + ' (' + fkc.referenced_col + ')',
                     ';')
              FROM sys.foreign_keys fk
              CROSS APPLY (
                  SELECT TOP 1
                         QUOTENAME(pc.name) AS parent_col,
                         QUOTENAME(rc.name) AS referenced_col
                    FROM sys.foreign_key_columns c
                    JOIN sys.columns pc ON pc.object_id = c.parent_object_id
                                       AND pc.column_id = c.parent_column_id
                    JOIN sys.columns rc ON rc.object_id = c.referenced_object_id
                                       AND rc.column_id = c.referenced_column_id
                   WHERE c.constraint_object_id = fk.object_id
                   ORDER BY c.constraint_column_id
              ) fkc
             WHERE fk.referenced_object_id = OBJECT_ID(@qualified));

        -- Non-constraint indexes, recreated after the swap.
        SET @idx = (
            SELECT STRING_AGG(
                     'CREATE ' + CASE WHEN i.is_unique = 1 THEN 'UNIQUE ' ELSE '' END
                     + 'INDEX ' + QUOTENAME(i.name) + ' ON ' + @qualified + ' (' + ix.cols + ')',
                     ';')
              FROM sys.indexes i
              CROSS APPLY (
                  SELECT STUFF((SELECT ',' + QUOTENAME(ic.name)
                                  FROM sys.index_columns c
                                  JOIN sys.columns ic ON ic.object_id = c.object_id
                                                     AND ic.column_id = c.column_id
                                 WHERE c.object_id = i.object_id AND c.index_id = i.index_id
                                 ORDER BY c.key_ordinal
                                   FOR XML PATH(''), TYPE).value('.', 'NVARCHAR(MAX)'), 1, 1, '') AS cols
              ) ix
             WHERE i.object_id = OBJECT_ID(@qualified)
               AND i.is_primary_key = 0 AND i.is_unique_constraint = 0
               AND i.type IN (1, 2));

        SET @sql = N'
BEGIN TRANSACTION;
BEGIN TRY
    ' + ISNULL(@fksDrop, N'') + N';

    CREATE TABLE ' + @shadow + N' (
        ' + QUOTENAME(@idCol) + N' INT IDENTITY(1, 1) NOT NULL,
        ' + @colDefs + N',
        CONSTRAINT ' + QUOTENAME(@pk + '_new') + N' PRIMARY KEY (' + QUOTENAME(@idCol) + N')
    );

    SET IDENTITY_INSERT ' + @shadow + N' ON;
    INSERT INTO ' + @shadow + N' (' + QUOTENAME(@idCol) + N', ' + @copyCols + N')
    SELECT ' + QUOTENAME(@idCol) + N', ' + @copyCols + N' FROM ' + @qualified + N';
    SET IDENTITY_INSERT ' + @shadow + N' OFF;

    DROP TABLE ' + @qualified + N';
    EXEC sp_rename ''' + @schema + '.' + @table + '_new'', ''' + @table + ''';

    ALTER TABLE ' + @qualified + N' DROP CONSTRAINT ' + QUOTENAME(@pk + '_new') + N';
    ALTER TABLE ' + @qualified + N' ADD CONSTRAINT ' + QUOTENAME(@pk)
        + N' PRIMARY KEY (' + QUOTENAME(@idCol) + N');

    ' + ISNULL(@defaults, N'') + N';
    ' + ISNULL(@idx, N'') + N';
    ' + ISNULL(@fksAdd, N'') + N';

    COMMIT TRANSACTION;
    PRINT ''  ' + @qualified + N' rebuilt'';
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH';

        EXEC sp_executesql @sql;
    END

    FETCH NEXT FROM rebuild INTO @table, @idCol;
END

CLOSE rebuild;
DEALLOCATE rebuild;
GO

-- Report the result, so a deploy log shows what happened.
SELECT 'core.Participant' AS TableName,
       COLUMNPROPERTY(OBJECT_ID('core.Participant'), 'ParticipantID', 'IsIdentity') AS IsIdentity,
       (SELECT COUNT(*) FROM core.Participant) AS Rows
UNION ALL
SELECT 'core.Registration',
       COLUMNPROPERTY(OBJECT_ID('core.Registration'), 'RegistrationID', 'IsIdentity'),
       (SELECT COUNT(*) FROM core.Registration);
GO
